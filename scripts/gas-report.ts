/**
 * pnpm contracts:gas: run contracts/test/gas/GasReport.t.sol and write docs/gas.md from the forge gas snapshots.
 * Numbers are execution gas of one warm external call each (forge `startSnapshotGas`/`stopSnapshotGas`),
 * excluding the 21k intrinsic cost and calldata.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { z } from "zod";
import { repoRoot } from "./lib/env";

const root = repoRoot();
const contractsDir = resolve(root, "contracts");

const ROWS: ReadonlyArray<{ key: string; label: string; note: string }> = [
  { key: "settle", label: "settle()", note: "root node, allowlisted payee, real USDC transferWithAuthorization" },
  { key: "reserve", label: "reserve()", note: "same checks and charge as settle, no token call" },
  { key: "release", label: "release()", note: "after validBefore, unexecuted: walks the node chain to refund spent" },
  { key: "escrowCreate", label: "escrow create()", note: "factory: terms check, CREATE2 clone, initialize" },
  { key: "fundSettleToEscrow", label: "fund: settle() to escrow", note: "treasury pays the order amount through the escrow payee rule" },
  { key: "fundMarkFunded", label: "fund: markFunded()", note: "escrow confirms balance >= price + bond" },
  { key: "reveal", label: "revealKey()", note: "seller reveals the delivery key" },
  { key: "accept", label: "accept()", note: "buyer-node signature, payout of price + bond to the seller" },
  { key: "refund", label: "claimTimeoutRefund()", note: "missed reveal: whole balance back to the treasury" },
  { key: "sweep", label: "sweep()", note: "USDC that arrived after the order closed: whole balance back to the treasury" },
];

execFileSync("forge", ["test", "--match-path", "test/gas/GasReport.t.sol"], { cwd: contractsDir, stdio: "inherit" });

const Snapshot = z.record(z.string(), z.coerce.bigint());
const snapshot = Snapshot.parse(JSON.parse(readFileSync(resolve(contractsDir, "snapshots", "GasReportTest.json"), "utf8")));
const forgeVersion = execFileSync("forge", ["--version"], { encoding: "utf8" }).split("\n")[0]?.trim() ?? "forge";
const fmt = (n: bigint): string => n.toLocaleString("en-US");

const lines = [
  "# Gas report",
  "",
  `Generated by \`pnpm contracts:gas\` on ${new Date().toISOString().slice(0, 10)} with ${forgeVersion}, solc 0.8.28, cancun, optimizer 200 runs.`,
  "Each row is the execution gas of one warm external call measured in `contracts/test/gas/GasReport.t.sol` against Circle's",
  "real USDC v2.2 bytecode on a local EVM (forge gas snapshots). Add roughly 21,000 intrinsic gas plus calldata for a full",
  "transaction. Treasury depth is 1 (root node pays); every extra delegation level adds one node walk to settle/reserve/release.",
  "",
  "| Operation | Gas | Notes |",
  "|---|---:|---|",
];
for (const row of ROWS) {
  const gas = snapshot[row.key];
  if (gas === undefined) throw new Error(`snapshot missing "${row.key}"; did GasReport.t.sol change?`);
  lines.push(`| ${row.label} | ${fmt(gas)} | ${row.note} |`);
}
lines.push("", "Source of truth: `contracts/snapshots/GasReportTest.json` (regenerated on every run, not committed).", "");
const out = resolve(root, "docs", "gas.md");
writeFileSync(out, lines.join("\n"));
console.log(`wrote docs/gas.md (${ROWS.length} rows)`);
