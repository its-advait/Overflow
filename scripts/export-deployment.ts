/**
 * Writes packages/schemas/deployments/base-sepolia.json from the latest Deploy.s.sol broadcast and
 * generates `as const` viem ABIs into packages/schemas/src/abi/ from contracts/out.
 *
 * Usage: pnpm contracts:export            (run by scripts/deploy.sh after a broadcast)
 *        pnpm contracts:export --abi-only (regenerate ABIs from contracts/out without a broadcast)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
// Subpath import: the package index re-exports ./abi, which this script generates.
import { CHAIN_ID, parseDeployments, USDC } from "@overflow/schemas/chain";
import { type Broadcast, broadcastTimestamp, initCodeMatcher, readBroadcast } from "./lib/broadcast.js";
import { loadEnv, repoRoot } from "./lib/env.js";

/** Contracts exported as ABIs when their artifact exists. */
const ABI_CONTRACTS = ["OverflowTreasury", "OverflowEscrowFactory", "OverflowEscrow"] as const;

function camel(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1);
}

function exportAbis(root: string): void {
  const abiDir = resolve(root, "packages/schemas/src/abi");
  mkdirSync(abiDir, { recursive: true });
  const exported: string[] = [];
  for (const name of ABI_CONTRACTS) {
    const artifact = resolve(root, "contracts/out", `${name}.sol`, `${name}.json`);
    if (!existsSync(artifact)) {
      console.log(`skip ${name}: no artifact at ${artifact}`);
      continue;
    }
    const { abi } = JSON.parse(readFileSync(artifact, "utf8")) as { abi: unknown[] };
    const ident = `${camel(name)}Abi`;
    const body =
      `// GENERATED by scripts/export-deployment.ts from contracts/out/${name}.sol/${name}.json (forge build).\n` +
      `// Do not edit by hand; rerun \`pnpm contracts:export --abi-only\`.\n` +
      `export const ${ident} = ${JSON.stringify(abi, null, 2)} as const;\n`;
    writeFileSync(resolve(abiDir, `${name}.ts`), body);
    exported.push(name);
    console.log(`wrote packages/schemas/src/abi/${name}.ts (${abi.length} entries)`);
  }
  if (exported.length === 0) {
    console.error("no artifacts found; run forge build in contracts/ first");
    process.exit(1);
  }
  const index =
    "// GENERATED by scripts/export-deployment.ts. Do not edit by hand.\n" +
    exported.map((n) => `export { ${camel(n)}Abi } from "./${n}";`).join("\n") +
    "\n";
  writeFileSync(resolve(abiDir, "index.ts"), index);
}

function main(): void {
  loadEnv();
  const root = repoRoot();
  if (process.argv.includes("--abi-only")) {
    exportAbis(root);
    return;
  }
  const runFile = resolve(root, "contracts/broadcast/Deploy.s.sol", String(CHAIN_ID), "run-latest.json");
  if (!existsSync(runFile)) {
    console.error(`no broadcast found at ${runFile}; run pnpm contracts:deploy first`);
    process.exit(1);
  }
  const run = JSON.parse(readFileSync(runFile, "utf8")) as Broadcast;

  // The escrow implementation is created by the factory's constructor, so it only appears as a nested create;
  // match it by the OverflowEscrow creation code from the same build.
  const escrowArtifact = resolve(root, "contracts/out/OverflowEscrow.sol/OverflowEscrow.json");
  const escrowCreationCode = existsSync(escrowArtifact)
    ? (JSON.parse(readFileSync(escrowArtifact, "utf8")) as { bytecode: { object: `0x${string}` } }).bytecode.object
    : null;
  if (!escrowCreationCode) console.log(`no OverflowEscrow artifact at ${escrowArtifact}; nested creates cannot be matched`);
  const summary = readBroadcast(run, { isEscrowInitCode: escrowCreationCode ? initCodeMatcher(escrowCreationCode) : () => false });
  for (const note of summary.notes) console.log(`note: ${note}`);

  const token = (process.env["TOKEN_ADDRESS"] ?? USDC.address) as `0x${string}`;
  const owner = process.env["OWNER_ADDRESS"];
  if (!owner) {
    console.error("OWNER_ADDRESS missing from env; it is recorded in the deployments file");
    process.exit(2);
  }

  const deployments = parseDeployments({
    chainId: CHAIN_ID,
    token,
    usdc: token,
    treasury: summary.treasury.address,
    escrowFactory: summary.escrowFactory?.address ?? null,
    escrowImplementation: summary.escrowImplementation?.address ?? null,
    owner,
    deployer: summary.treasury.from,
    deployBlock: summary.deployBlock.toString(),
    deployedAt: broadcastTimestamp(run).toISOString(),
    txs: summary.txs,
  });

  const outDir = resolve(root, "packages/schemas/deployments");
  mkdirSync(outDir, { recursive: true });
  const outFile = resolve(outDir, "base-sepolia.json");
  writeFileSync(outFile, JSON.stringify(deployments, null, 2) + "\n");
  console.log(`wrote ${outFile}`);

  // Static accessor so apps get the addresses without reading the file at runtime.
  const depTs =
    "// GENERATED by scripts/export-deployment.ts. Do not edit by hand; rerun `pnpm contracts:export`.\n" +
    'import json from "../deployments/base-sepolia.json" with { type: "json" };\n' +
    'import { parseDeployments } from "./chain";\n\n' +
    "/** Addresses of the current Base Sepolia deployment (packages/schemas/deployments/base-sepolia.json). */\n" +
    "export const BASE_SEPOLIA_DEPLOYMENT = parseDeployments(json);\n";
  writeFileSync(resolve(root, "packages/schemas/src/deployments.ts"), depTs);
  const indexFile = resolve(root, "packages/schemas/src/index.ts");
  const index = readFileSync(indexFile, "utf8");
  if (!index.includes('from "./deployments"')) {
    writeFileSync(indexFile, index.trimEnd() + "\nexport * from \"./deployments\";\n");
  }
  console.log("wrote packages/schemas/src/deployments.ts");

  exportAbis(root);
}

main();
