import { BASE_SEPOLIA_EXPLORER } from "@overflow/schemas";
import type { CaseResult, Mode, ResultsFile, RunRecord, Verdict } from "./types.js";

// ---------------------------------------------------------------------------
// Results table: docs/proof/results.json keeps the last fork run and the last
// live run; docs/proof/results.md is rendered from it. Fork transaction hashes
// exist only on the local anvil fork and are labeled so: they are never linked
// to Basescan. A BLOCKED case counts as not passed.
// ---------------------------------------------------------------------------

export function summarize(results: readonly CaseResult[]): RunRecord["summary"] {
  const count = (v: Verdict) => results.filter((r) => r.verdict === v).length;
  return { total: results.length, passed: count("PASS"), failed: count("FAIL"), blocked: count("BLOCKED"), notRun: count("NOT_RUN") };
}

/** Non-zero when any case failed or was blocked. */
export function exitCodeFor(run: Pick<RunRecord, "results">): number {
  return run.results.some((r) => r.verdict === "FAIL" || r.verdict === "BLOCKED") ? 1 : 0;
}

export function mergeRun(file: ResultsFile | undefined, run: RunRecord): ResultsFile {
  return { generatedBy: "pnpm proof (scripts/proof/run.ts)", fork: file?.fork, live: file?.live, [run.mode]: run };
}

const short = (h: string): string => `${h.slice(0, 10)}…${h.slice(-6)}`;

export function txCell(mode: Mode, hash: string | undefined): string {
  if (!hash) return "—";
  if (mode === "live") return `[${short(hash)}](${BASE_SEPOLIA_EXPLORER}/tx/${hash})`;
  return `anvil fork (local, not on Basescan): \`${hash}\``;
}

export function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\r?\n/g, "<br>");
}

const VERDICT_MARK: Record<Verdict, string> = { PASS: "PASS", FAIL: "**FAIL**", BLOCKED: "**BLOCKED**", NOT_RUN: "NOT RUN" };

export function renderRun(run: RunRecord): string {
  const title = run.mode === "fork" ? "Fork run (anvil fork of Base Sepolia)" : "Live run (Base Sepolia)";
  const s = run.summary;
  const lines: string[] = [];
  lines.push(`## ${title}`, "");
  lines.push(`- Run: ${run.startedAt} to ${run.finishedAt}`);
  lines.push(`- Chain: ${run.chain.chainId}, blocks ${run.chain.startBlock} to ${run.chain.endBlock}${run.chain.forkBlock ? `, forked at Base Sepolia block ${run.chain.forkBlock}` : ""}`);
  lines.push(`- Node: ${run.chain.node}`);
  lines.push(`- Contracts: treasury \`${run.contracts.treasury}\`, escrow factory \`${run.contracts.escrowFactory}\`, USDC \`${run.contracts.usdc}\`, owner \`${run.contracts.owner}\``);
  const actors = Object.entries(run.actors).map(([k, v]) => `${k} \`${v}\``);
  if (actors.length) lines.push(`- Actors: ${actors.join(", ")}`);
  lines.push(`- Result: **${s.passed}/${s.total} passed**, ${s.failed} failed, ${s.blocked} blocked, ${s.notRun} not run`);
  if (run.mode === "fork") lines.push("- Fork transaction hashes exist only on the local anvil fork (state copied from Base Sepolia); they are not on Basescan.");
  for (const n of run.notes) lines.push(`- ${n}`);
  lines.push("");
  lines.push("| # | Planted error | Expected | Actual | Pass/fail | Tx |");
  lines.push("|---|---|---|---|---|---|");
  for (const r of run.results) {
    const actual = r.reasons?.length ? `${r.actual}${r.actual ? "<br>" : ""}${r.reasons.map(cell).join("<br>")}` : cell(r.actual);
    lines.push(`| ${r.id} | ${cell(r.plantedError)} | ${cell(r.expected)} | ${actual} | ${VERDICT_MARK[r.verdict]} | ${r.onchain ? txCell(run.mode, r.txHash) : "—"} |`);
  }
  lines.push("");
  const withTxs = run.results.filter((r) => r.txs.length > 0);
  if (withTxs.length) {
    lines.push(`<details><summary>Every transaction the ${run.mode} run sent, by case</summary>`, "");
    for (const r of withTxs) {
      lines.push(`- **${r.id}** ${r.txs.map((t) => `${t.label} (${t.status}) ${run.mode === "live" ? `[${short(t.hash)}](${BASE_SEPOLIA_EXPLORER}/tx/${t.hash})` : `\`${t.hash}\``}`).join("; ")}`);
    }
    lines.push("", "</details>", "");
  }
  return lines.join("\n");
}

export function renderResults(file: ResultsFile): string {
  const out: string[] = [];
  out.push("# Planted-error proof results", "");
  out.push(
    "Generated by `pnpm proof --fork` / `pnpm proof --live` (scripts/proof/run.ts) from docs/SPEC.md \"Planted-error set with answer key\". " +
      "Every Actual cell comes from a confirmed chain event, a decoded revert of a mined transaction, or a real API/database answer; " +
      "SIMULATED parts (sellers, datasets, attacker, company books) are labeled. The expected column is the answer key verbatim and is never edited to make a case pass.",
    "",
  );
  if (file.fork) out.push(renderRun(file.fork));
  else out.push("## Fork run", "", "Not run yet.", "");
  if (file.live) out.push(renderRun(file.live));
  else out.push("## Live run", "", "Not run yet.", "");
  return `${out.join("\n").trimEnd()}\n`;
}
